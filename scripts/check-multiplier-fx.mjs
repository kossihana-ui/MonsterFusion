import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';
const server = await createServer({server:{middlewareMode:true},appType:'custom'});
try {
  const {multiplierPresentation: present} = await server.ssrLoadModule('/src/components/MultiplierEffect.tsx');
  const damage = {type:'damage',hit:1,hits:1,amount:15,critical:false};
  const up = {source:'attackUp',reason:'攻撃力上昇',factor:2};
  const seed = {source:'seed',reason:'種',factor:1.5};
  assert.equal(present(damage),null);
  assert.equal(present({...damage,boosts:[{source:'element',factor:2}]}),null);
  assert.equal(present({...damage,boosts:[{source:'targetNotDefending',factor:.5}]}),null);
  assert.equal(present({...damage,boosts:[seed]}).factor,1.5);
  const event = {...damage,critical:true,boosts:[up,seed,{source:'element',factor:.5}]};
  const original = JSON.stringify(event);
  assert.deepEqual(present(event),{factor:3,critical:true,reason:'攻撃力上昇 ×2 / 種 ×1.5'});
  assert.equal(JSON.stringify(event),original);
  assert.equal(present({...event,hit:1,hits:2}),null);
  assert.equal(present({...event,hit:2,hits:2}).factor,3);
  assert.equal(present({type:'heal',amount:30}),null);
  const game = await server.ssrLoadModule('/src/mocks/game.ts');
  const core = await server.ssrLoadModule('@core/core/index.ts');
  const ignis = game.initialMonsters[1];
  const saved = game.getMoveLoadout(ignis.id).skillIds;
  assert.ok(game.setMoveLoadout(ignis.id,['ram-charge']).ok);
  let duel = game.createBattle(ignis,game.initialMonsters[0]).coreState;
  const rng = core.createSeededRandom(42);
  const player = core.createScriptedPolicy([{kind:'skill',skillId:'ram-charge',targetId:duel.combatants[1].id},{kind:'attack',targetId:duel.combatants[1].id}]);
  const enemy = core.createScriptedPolicy([{kind:'defend'}]);
  duel = core.stepTurn(duel,[core.createScriptedPolicy([{kind:'defend'}]),enemy],rng);
  duel = core.stepTurn(duel,[player,enemy],rng);
  const start = duel.log.length;
  duel = core.stepTurn(duel,[player,enemy],rng);
  const actual = duel.log.slice(start).flatMap(e=>e.effects??[]).find(e=>e.type==='damage'&&e.actorId===duel.combatants[0].id);
  assert.equal(present(actual).factor,2,'real ram-charge buff reaches presentation');
  assert.ok(game.setMoveLoadout(ignis.id,saved).ok);
  const wav = readFileSync('public/sounds/orchestra-hit.wav');
  assert.equal(wav.toString('ascii',0,4),'RIFF');
  const duration=wav.readUInt32LE(40)/wav.readUInt32LE(28);
  assert.ok(duration>=.4&&duration<=.8);
  assert.equal(wav.readInt16LE(wav.length-2),0);
  console.log('Multiplier: normal, element-only, reduction, decimal, stacked, critical, multi-hit, support, immutability and audio passed.');
} finally {await server.close();}
