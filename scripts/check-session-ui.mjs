import assert from 'node:assert/strict';
import {createServer} from 'vite';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
try {
  const game=await server.ssrLoadModule('/src/mocks/game.ts');
  const api=game.gameAdapter;
  const initial=game.getGameSession();
  let notices=0;const off=game.subscribeSession(()=>notices++);
  const [a,b,c]=game.initialMonsters;
  game.enterArena(a.id);
  assert.deepEqual(game.getGameSession().deployed,[a.id]);
  await assert.rejects(api.fuseMonsters(a,b),/戦闘中/);
  assert.equal(game.getGameSession().owned.length,3);
  const otherChild=(await api.fuseMonsters(b,c)).child;
  assert.equal(game.getGameSession().owned.length,2,'non-deployed parents remain usable');
  game.leaveArena();
  assert.equal(game.getGameSession().deployed.length,0);
  const child=(await api.fuseMonsters(a,otherChild)).child;
  assert.equal(game.getGameSession().owned.length,1);
  assert.equal(initial.owned.length,3,'old core snapshot unchanged');
  assert.equal(game.getGameSession().history.length,5);
  await assert.rejects(api.fuseMonsters(a,child),/手元にいない/);
  const before=game.getGameSession();
  assert.equal(game.makeSoul({partIds:[]},'missing-parts').ok,false);
  assert.equal(game.getGameSession(),before);
  let battle=game.enterArena(child.id);
  for(let i=0;i<200&&battle.status==='active';i++) battle=await api.calculateBattleTurn(battle,'defend');
  assert.equal(battle.status,'lost');assert.equal(game.getGameSession().status,'gameOver');
  assert.equal(game.getGameSession().owned.length,0);
  const ended=game.getGameSession();
  await api.calculateBattleTurn(battle,'attack');
  assert.equal(game.makeSoul({partIds:[]},'after-end').ok,false);
  game.leaveArena();assert.equal(game.getGameSession(),ended);
  assert.ok(notices>0);off();
  game.restartGame();
  assert.equal(game.getGameSession().owned.length,3);
  assert.equal(game.getGameSession().status,'playing');
  assert.equal(game.getPartInventory().stacks.length,0);
  console.log('Core session UI: deployment, fusion, history, no-spend refusal, defeat, terminal game over, subscription and restart passed.');
} finally {await server.close();}
